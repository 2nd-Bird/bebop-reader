const PC={C:0,D:2,E:4,F:5,G:7,A:9,B:11};
const MAJOR=[0,2,4,5,7,9,11];
const SYL=['ド','レ','ミ','ファ','ソ','ラ','シ'];
function pitchClass(p){if(!p)return null;let pc=PC[p[0]];if(p.includes('#')||p.includes('♯'))pc++;if(p.includes('b')||p.includes('♭'))pc--;return (pc+12)%12;}
export function solfege(p,key='C'){
  const pc=pitchClass(p), tonic=pitchClass(key);if(pc==null||tonic==null)return '・';
  const rel=(pc-tonic+12)%12;const i=MAJOR.indexOf(rel);return i>=0?SYL[i]:'・';
}
